// Generates src/lib/og-emoji.ts: a map of the emoji used on the OG card to
// base64 data URIs, so the card renders them with zero runtime/CDN dependency.
//
// NOTE: renders from the macOS system font "Apple Color Emoji" via
// scripts/render-emoji.swift at its largest bitmap strike (160 px) — packaged
// emoji sets top out at a blurry 64 px. macOS only; the output is committed,
// so this only needs re-running when the emoji set changes:
// `node scripts/generate-og-emoji.mjs`. The PNGs are Apple's proprietary
// emoji artwork.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// Every emoji the card can show: the temperature-tier reactions plus the vehicles.
const EMOJI = [
  "🔥",
  "💀",
  "🌡️",
  "😭",
  "☀️",
  "😩",
  "🌤️",
  "😒",
  "☁️",
  "🙄",
  "🌬️",
  "😤",
  "❄️",
  "😠",
  "🧊",
  "🤬",
  "🖕",
  "🚋",
  "🚌",
];

const renderer = fileURLToPath(new URL("./render-emoji.swift", import.meta.url));
const workDir = mkdtempSync(join(tmpdir(), "og-emoji-"));

const entries = EMOJI.map((emoji) => {
  const out = join(workDir, "glyph.png");
  execFileSync("swift", [renderer, emoji, out], { stdio: ["ignore", "inherit", "inherit"] });
  const base64 = readFileSync(out).toString("base64");
  return `  "${emoji}": "data:image/png;base64,${base64}",`;
});

rmSync(workDir, { recursive: true, force: true });

const out = `// GENERATED by scripts/generate-og-emoji.mjs — do not edit by hand.
// PNGs are Apple's proprietary emoji artwork (macOS Apple Color Emoji font).
export const OG_EMOJI: Record<string, string> = {
${entries.join("\n")}
};
`;

writeFileSync(fileURLToPath(new URL("../src/lib/og-emoji.ts", import.meta.url)), out);
console.log(`Wrote ${EMOJI.length} emoji to src/lib/og-emoji.ts`);
