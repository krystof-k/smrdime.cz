// Generates src/lib/og-emoji.ts: a map of the emoji used on the OG card to
// base64 data URIs, so the card renders them with zero runtime/CDN dependency.
//
// NOTE: the PNGs come from emoji-datasource-apple — Apple's proprietary emoji
// artwork. Re-run with `node scripts/generate-og-emoji.mjs` if the emoji set
// changes.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const IMG_DIR = fileURLToPath(
  new URL("../node_modules/emoji-datasource-apple/img/apple/64/", import.meta.url),
);

// Every emoji the card can show: the temperature-tier reactions plus the tram.
const EMOJI = [
  "🔥",
  "💀",
  "🌡️",
  "😭",
  "☀️",
  "😩",
  "🌤️",
  "😒",
  "☁️",
  "🙄",
  "🌬️",
  "😤",
  "❄️",
  "😠",
  "🧊",
  "🤬",
  "🖕",
  "🚋",
];

function codepoints(emoji) {
  return [...emoji].map((c) => c.codePointAt(0).toString(16));
}

// Try the full codepoint filename, then a couple of common variants (Apple's
// files sometimes drop the FE0F variation selector).
function fileFor(emoji) {
  const cps = codepoints(emoji);
  const candidates = [cps.join("-"), cps.filter((c) => c !== "fe0f").join("-")];
  for (const name of candidates) {
    const path = `${IMG_DIR}${name}.png`;
    if (existsSync(path)) return path;
  }
  throw new Error(`No Apple PNG for ${emoji} (tried ${candidates.join(", ")})`);
}

const entries = EMOJI.map((emoji) => {
  const base64 = readFileSync(fileFor(emoji)).toString("base64");
  return `  "${emoji}": "data:image/png;base64,${base64}",`;
});

const out = `// GENERATED by scripts/generate-og-emoji.mjs — do not edit by hand.
// PNGs are Apple's proprietary emoji artwork (emoji-datasource-apple).
export const OG_EMOJI: Record<string, string> = {
${entries.join("\n")}
};
`;

writeFileSync(fileURLToPath(new URL("../src/lib/og-emoji.ts", import.meta.url)), out);
console.log(`Wrote ${EMOJI.length} emoji to src/lib/og-emoji.ts`);
