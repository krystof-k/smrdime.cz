// Generates src/lib/og-fonts.ts: the five Geist faces the OG card uses,
// subset to the card's charset and inlined as base64, so a cold worker
// isolate renders with zero font fetches (previously five Google Fonts
// round trips — the main reason OG scrapers timed out on cold renders).
// Re-run after upgrading the geist package: node scripts/generate-og-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

// Every character the card can draw: the Czech alphabet, digits for counts
// and the timestamp, and the punctuation the headline and stamp use.
const CHARSET =
  "AÁBCČDĎEÉĚFGHIÍJKLMNŇOÓPQRŘSŠTŤUÚŮVWXYZÝŽaábcčdďeéěfghiíjklmnňoópqrřsštťuúůvwxyzýž0123456789 .,:%°()–—„“?!/+-";

const FONTS = [
  { name: "Geist", weight: 100, file: "geist-sans/Geist-Thin.ttf" },
  { name: "Geist", weight: 400, file: "geist-sans/Geist-Regular.ttf" },
  { name: "Geist", weight: 900, file: "geist-sans/Geist-Black.ttf" },
  { name: "Geist Mono", weight: 400, file: "geist-mono/GeistMono-Regular.ttf" },
  { name: "Geist Mono", weight: 900, file: "geist-mono/GeistMono-Black.ttf" },
];

const entries = await Promise.all(
  FONTS.map(async ({ name, weight, file }) => {
    const ttf = readFileSync(
      fileURLToPath(new URL(`../node_modules/geist/dist/fonts/${file}`, import.meta.url)),
    );
    // Plain TrueType output — Satori reads it directly, no decompression.
    const subset = await subsetFont(ttf, CHARSET, { targetFormat: "sfnt" });
    return `  { name: ${JSON.stringify(name)}, weight: ${weight}, base64: "${subset.toString("base64")}" },`;
  }),
);

const out = `// GENERATED by scripts/generate-og-fonts.mjs — do not edit by hand.
// Geist is licensed under the SIL Open Font License 1.1 (see the geist
// npm package); subsetting and embedding are permitted.
export const OG_FONTS: Array<{ name: string; weight: 100 | 400 | 900; base64: string }> = [
${entries.join("\n")}
];
`;

writeFileSync(fileURLToPath(new URL("../src/lib/og-fonts.ts", import.meta.url)), out);
console.log(`Wrote ${FONTS.length} fonts to src/lib/og-fonts.ts`);
